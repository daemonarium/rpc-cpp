class Person {
  public:
    std::string name;
    int age;

    Person() : name(""), age(0) {}
    Person(std::string namep, int agep) : name(namep), age(agep) {}

    std::string get_name() const { return name; }
    int get_age() const { return age; }
    void set_name(std::string namep) { name = namep; }
    void set_age(int agep) { age = agep; }

    static Person& get_rpc_object(std::uint32_t id);
};

std::vector<Person> people;

Person& Person::get_rpc_object(std::uint32_t id) {
  if(id >= people.size()) {
    people.resize(id + 1);
  }
  return people[id];
}
  
template <typename rpc_client_type>
class PersonRpc { // should be generated by a script
  public:
    using id_type = std::uint32_t;

    PersonRpc(std::shared_ptr<rpc_client_type> rpc_client, id_type id) : rpc_client_(rpc_client), id_(id) {}
    ~PersonRpc() {}
    
    std::shared_ptr<serialization::promise<std::string>> get_name() {
      return rpc_client_->template call_method<id_type, std::string>(1, id_);
    }

    std::shared_ptr<serialization::promise<int>> get_age() {
      return rpc_client_->template call_method<id_type, int>(2, id_);
    }

    std::shared_ptr<serialization::promise<void>> set_name(std::string name) {
      return rpc_client_->template call_method<id_type, void>(3, id_, name);
    }

    std::shared_ptr<serialization::promise<void>> set_age(int age) {
      return rpc_client_->template call_method<id_type, void>(4, id_, age);
    }
    
  private:
    std::shared_ptr<rpc_client_type> rpc_client_;
    id_type id_;
};

int main(int argc, char** argv) {  

  serialization::loopback_rpc loopbackRpc;
 
  Person person;

  loopbackRpc.register_rpc(person);

  std::cout << "Known types:" << std::endl;

  for (const auto& type : loopbackRpc.registry.get_types()) {
    std::cout << *type << std::endl;
  }  
  std::cout << "--------------------------------" << std::endl; 

  PersonRpc<typename serialization::loopback_rpc::rpc_client_type> zeroPersonRpc(loopbackRpc.rpc_client, 0);
  PersonRpc<typename serialization::loopback_rpc::rpc_client_type> onePersonRpc(loopbackRpc.rpc_client, 1);

  zeroPersonRpc.set_name("John")->on_resolved([](void) {
    std::cout << "zero person name set" << std::endl;
  });
  zeroPersonRpc.set_age(30)->on_resolved([](void) {
    std::cout << "zero person age set" << std::endl;
  });
  onePersonRpc.set_name("Jane")->on_resolved([](void) {
    std::cout << "one person name set" << std::endl;
  });
  onePersonRpc.set_age(20)->on_resolved([](void) {
    std::cout << "one person age set" << std::endl;
  });
  zeroPersonRpc.get_name()->on_resolved([](std::string result) {
    std::cout << "zero person name: " << result << std::endl;
  });
  zeroPersonRpc.get_age()->on_resolved([](int result) {
    std::cout << "zero person age: " << result << std::endl;
  });
  onePersonRpc.get_name()->on_resolved([](std::string result) {
    std::cout << "one person name: " << result << std::endl;
  });
  onePersonRpc.get_age()->on_resolved([](int result) {
    std::cout << "one person age: " << result << std::endl;
  });
 
  return 0;


}