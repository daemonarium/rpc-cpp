template <typename rpc_client_type>
class SimpleRpc { // should be generated by a script
  public:
    SimpleRpc(std::shared_ptr<rpc_client_type> rpc_client) : rpc_client_(rpc_client) {}
    ~SimpleRpc() {}
    
    std::shared_ptr<serialization::promise<std::string>> hello() {
      return rpc_client_->template call<std::string>(0);
    }

    std::shared_ptr<serialization::promise<std::uint64_t>> fib(std::uint64_t n) {
      return rpc_client_->template call<std::uint64_t>(1, n);
    }

    std::shared_ptr<serialization::promise<std::string>> hello_promise() {
      return rpc_client_->template call<std::string>(2);
    }
    
  private:
    std::shared_ptr<rpc_client_type> rpc_client_;
};

int main(int argc, char** argv) {  

  serialization::loopback_rpc loopbackRpc;
 
  Simple simple;

  auto simpleType = loopbackRpc.register_rpc(simple);

  std::cout << "Simple type: " << *simpleType << std::endl;
  std::cout << "Known types:" << std::endl;

  for (const auto& type : loopbackRpc.registry.get_types()) {
    std::cout << *type << std::endl;
  }  
  std::cout << "--------------------------------" << std::endl; 

  SimpleRpc<typename serialization::loopback_rpc::rpc_client_type> simpleRpc(loopbackRpc.rpc_client);

  simpleRpc.hello()->on_resolved([](std::string result) {
    std::cout << "Hello result: " << result << std::endl;
  });
  simpleRpc.fib(6)->on_resolved([](std::uint64_t result) {
    std::cout << "Fib result: " << result << std::endl;
  });
  simpleRpc.hello_promise()->on_resolved([](std::string result) {
    std::cout << "Hello promise result: " << result << std::endl;
  });
  return 0;


}